// Writes every county in the given states, from static/counties, as seed rows for the
// place selector. Run from packages/admin: `node scripts/county-seeds.mjs OR UT`, then
// prettier on the output.
// The output stands in for real comhairle Areas until #509 imports them.

import { readFileSync, writeFileSync } from 'node:fs';

const OUTPUT = 'src/lib/components/place-selector/county-seeds.ts';

function bboxOf(geometry) {
	const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
	const points = polygons.flat(2);
	const xs = points.map(([x]) => x);
	const ys = points.map(([, y]) => y);
	// Round outward so the box still covers the whole county.
	const down = (n) => Math.floor(n * 100) / 100;
	const up = (n) => Math.ceil(n * 100) / 100;
	return [down(Math.min(...xs)), down(Math.min(...ys)), up(Math.max(...xs)), up(Math.max(...ys))];
}

function countiesIn(abbreviation) {
	const file = JSON.parse(readFileSync(`static/counties/counties_${abbreviation}.geojson`, 'utf8'));
	return file.features.map(({ properties, geometry }) => ({
		geoid: properties.GEO_ID.slice(-5),
		name: `${properties.NAME} ${properties.LSAD}`,
		state: properties.STATE,
		bbox: bboxOf(geometry)
	}));
}

const states = process.argv.slice(2);
if (states.length === 0) {
	console.error('Usage: node scripts/county-seeds.mjs OR UT');
	process.exit(1);
}

const rows = states
	.flatMap(countiesIn)
	.sort((a, b) => a.state.localeCompare(b.state) || a.name.localeCompare(b.name));

const body = rows
	.map(
		(row) =>
			`\t{ geoid: '${row.geoid}', name: '${row.name.replace(/'/g, "\\'")}', state: '${row.state}', bbox: [${row.bbox.join(', ')}] }`
	)
	.join(',\n');

writeFileSync(
	OUTPUT,
	`// Generated by scripts/county-seeds.mjs from static/counties (${states.join(', ')}). Rerun it rather than\n// editing by hand.

import type { CountySeed } from './fixture';

export const COUNTY_SEEDS: CountySeed[] = [
${body}
];
`
);

console.log(`Wrote ${rows.length} counties to ${OUTPUT}`);
